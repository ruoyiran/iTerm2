const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const path = 'sources/Browser/Automation/browser-automation.js';
assert.ok(fs.existsSync(path), 'Browser DOM implementation must exist');
const body = fs.readFileSync(path, 'utf8');
const dom = new JSDOM('<!doctype html><html><body><h1>Title</h1><div>Plain content</div><label for="name">Name</label><input id="name"><button id="button">Go</button><input type="file" id="file"><input type="password" value="secret"><div hidden><button>Hidden</button></div></body></html>', {url: 'https://example.com', runScripts: 'outside-only'});
const w = dom.window;
w.HTMLElement.prototype.getBoundingClientRect = function() { return {x:0,y:0,width:100,height:20}; };
w.HTMLElement.prototype.scrollIntoView = function() {};
const invoke = w.eval('(async function(action,args,expectedOrigin,deadline){' + body + '})');
(async () => {
  const call = (action,args={}) => invoke(action,args,'https://example.com',Date.now()+10000);
  const snapshot = await call('snapshot');
  assert.ok(snapshot.generation);
  assert.ok(snapshot.nodes.some(n=>n.role==='heading' && n.name==='Title'));
  assert.ok(!snapshot.nodes.some(n=>n.name==='Hidden'));
  assert.ok(snapshot.nodes.some(n=>n.name==='Plain content'));
  assert.ok(!JSON.stringify(snapshot).includes('secret'));
  const input = snapshot.nodes.find(n=>n.tag==='input' && n.name==='Name');
  let events=[]; w.document.querySelector('#name').addEventListener('input',()=>events.push('input'));
  w.document.querySelector('#name').addEventListener('change',()=>events.push('change'));
  const fill=await call('fill',{generation:snapshot.generation,ref:input.ref,value:'Ada'});
  assert.equal(fill.filled,true); assert.equal(w.document.querySelector('#name').value,'Ada');
  assert.deepEqual(events,['input','change']);
  const file=snapshot.nodes.find(n=>n.tag==='input' && n.input_type==='file');
  assert.equal((await call('click',{generation:snapshot.generation,ref:file.ref})).error_code,'unsupported');
  const next=await call('snapshot');
  assert.equal((await call('fill',{generation:snapshot.generation,ref:input.ref,value:'late'})).error_code,'stale_reference');
  assert.equal(w.document.querySelector('#name').value,'Ada');
  const current=next.nodes.find(n=>n.tag==='input' && n.name==='Name');
  w.document.querySelector('#name').remove();
  assert.equal((await call('click',{generation:next.generation,ref:current.ref})).error_code,'element_not_found');
  assert.equal((await invoke('snapshot',{},'https://other.com',Date.now()+1000)).error_code,'navigation_changed');
  assert.equal((await invoke('snapshot',{},'https://example.com',Date.now()-1)).error_code,'timeout');
  assert.equal((await call('press_key',{generation:next.generation,key:'Meta+v'})).error_code,'unsupported');
  assert.equal((await call('wait',{state:'attached',selector:'#button'})).matched,true);
  assert.equal((await call('wait',{state:'detached',selector:'#missing'})).matched,true);
  const same = w.document.createElement('iframe');
  same.src = 'https://example.com/frame'; w.document.body.appendChild(same);
  same.contentDocument.open(); same.contentDocument.write('<input aria-label="Frame name">'); same.contentDocument.close();
  same.contentWindow.HTMLElement.prototype.getBoundingClientRect = w.HTMLElement.prototype.getBoundingClientRect;
  const cross = w.document.createElement('iframe'); cross.src = 'https://other.com/frame'; w.document.body.appendChild(cross);
  const framed = await call('snapshot');
  assert.equal(framed.unsupported_frames,1);
  const child = framed.nodes.find(n=>n.name==='Frame name'); assert.ok(child);
  assert.equal((await call('fill',{generation:framed.generation,ref:child.ref,value:'Child'})).filled,true);
  const childNode = same.contentDocument.querySelector('input');
  same.remove();
  assert.equal((await call('fill',{generation:framed.generation,ref:child.ref,value:'Detached'})).error_code,'element_not_found');
  assert.equal(childNode.value,'Child');
  w.document.querySelector('#file').focus();
  assert.equal((await call('press_key',{generation:framed.generation,key:'Enter'})).error_code,'unsupported');
  const evaluateBody = fs.readFileSync('sources/Browser/Automation/browser-automation-evaluate.js','utf8');
  const evaluate = w.eval('(async function(expression,expectedOrigin,deadline){' + evaluateBody + '})');
  assert.equal((await evaluate('return document.querySelector("#button").textContent','https://example.com',Date.now()+1000)).value,'Go');
  assert.equal((await evaluate('return undefined','https://example.com',Date.now()+1000)).value,null);
  assert.equal((await evaluate('return 1n','https://example.com',Date.now()+1000)).error_code,'javascript_error');
  assert.equal((await evaluate('return 1','https://other.com',Date.now()+1000)).error_code,'navigation_changed');
  console.log('PASS: DOM snapshots, input events, unsafe input, stale/detached refs, origin/deadline, key and wait');
  w.close();
})().catch(error => { console.error(error); w.close(); process.exitCode=1; });
